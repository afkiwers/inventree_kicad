class SupplierFilter(views.APIView):
    """Read / update the list of suppliers whose data is added to KiCad parts.

    - GET: return the selected supplier IDs
    - PUT: replace the selected supplier IDs (an empty list means all suppliers)
    """

    permission_classes = [
        permissions.IsAdminUser,
    ]

    def get(self, request, *args, **kwargs):
        """Return the selected supplier IDs"""
        plugin = kwargs["plugin"]
        return response.Response({"suppliers": plugin.get_supplier_filter()})

    def put(self, request, *args, **kwargs):
        """Replace the selected supplier IDs"""
        plugin = kwargs["plugin"]
        suppliers = request.data.get("suppliers", [])

        if not isinstance(suppliers, list) or not all(
            str(x).isdigit() for x in suppliers
        ):
            return response.Response(
                {"suppliers": "Expected a list of supplier IDs"}, status=400
            )

        plugin.set_supplier_filter(suppliers)
        return response.Response({"suppliers": plugin.get_supplier_filter()})


class FieldMapping(views.APIView):
    """Read / update the field mapping, which renames fields sent to KiCad.

    - GET: return the mapping and a list of known field names (for autocompletion)
    - PUT: {"mapping": [{"from": str, "to": str}, ...]} replaces the mapping.
      Invalid rows return a 400 response with {"errors": {<row index>: <reason>}}
    """

    permission_classes = [
        permissions.IsAdminUser,
    ]

    # Field names generated by the plugin (besides the part parameter names)
    PLUGIN_FIELD_NAMES = [
        "IPN",
        "Part URL",
        "Manufacturer_1",
        "MPN_1",
        "Supplier_1_1",
        "SPN_1_1",
        "Supplier_1",
        "SPN_1",
    ]

    def get_suggestions(self):
        """Return the known field names: plugin fields and all parameter template names."""
        try:
            from common.models import ParameterTemplate
        except ImportError:  # pragma: no cover
            from part.models import PartParameterTemplate as ParameterTemplate

        names = set(ParameterTemplate.objects.values_list("name", flat=True))
        names = {
            name
            for name in names
            if name and name.lower() not in serializers.KICAD_PROTECTED_FIELDS
        }

        return self.PLUGIN_FIELD_NAMES + sorted(
            names - set(self.PLUGIN_FIELD_NAMES), key=str.lower
        )

    @staticmethod
    def clean_mapping(rows):
        """Validate the submitted rows; return (cleaned rows, {row index: error})."""
        cleaned = []
        errors = {}
        sources = set()
        targets = set()

        for index, row in enumerate(rows):
            if not isinstance(row, dict):
                errors[index] = "Invalid entry"
                continue

            source = str(row.get("from") or "").strip()
            target = str(row.get("to") or "").strip()

            if not source and not target:
                # Empty row - ignore
                continue

            if not source or not target:
                errors[index] = "Enter both field names"
            elif source.lower() in serializers.KICAD_PROTECTED_FIELDS:
                errors[index] = (
                    f"'{source}' is a protected KiCad field and cannot be renamed"
                )
            elif target.lower() in serializers.KICAD_PROTECTED_FIELDS:
                errors[index] = f"'{target}' is a protected KiCad field name"
            elif source == target:
                errors[index] = "The new name is the same as the field name"
            elif source.lower() in sources:
                errors[index] = f"'{source}' is already renamed in another row"
            elif target.lower() in targets:
                errors[index] = (
                    f"'{target}' is already used as a new name in another row"
                )
            else:
                sources.add(source.lower())
                targets.add(target.lower())
                cleaned.append({"from": source, "to": target})

        return cleaned, errors

    def get(self, request, *args, **kwargs):
        """Return the field mapping and the known field names"""
        plugin = kwargs["plugin"]

        return response.Response({
            "mapping": plugin.get_field_mapping(),
            "suggestions": self.get_suggestions(),
        })

    def put(self, request, *args, **kwargs):
        """Replace the field mapping"""
        plugin = kwargs["plugin"]
        rows = request.data.get("mapping", [])

        if not isinstance(rows, list):
            return response.Response(
                {"errors": {"mapping": "Expected a list of field renames"}}, status=400
            )

        cleaned, errors = self.clean_mapping(rows)

        if errors:
            return response.Response({"errors": errors}, status=400)

        plugin.set_field_mapping(cleaned)
        return response.Response({"mapping": plugin.get_field_mapping()})


class StockFormatPreview(views.APIView):
    """Preview the stock count display format using an example part.

    - POST: {"format": "<format string>"} -> {"preview": "<formatted description>"}
      or a 400 response with {"error": "<reason>"} if the format is invalid
    """

    permission_classes = [
        permissions.IsAdminUser,
    ]

    EXAMPLE_PART = SimpleNamespace(
        name="RES-10K-0603",
        IPN="R-0001",
        description="Resistor 10k 1% 0603",
        revision="A",
        used_in_count=3,
    )
    EXAMPLE_STOCK = Decimal(1250)

    def post(self, request, *args, **kwargs):
        """Return the example description for the provided format string"""
        format_string = request.data.get("format", "")

        if not isinstance(format_string, str):
            return response.Response({"error": "Expected a string"}, status=400)

        try:
            preview = serializers.format_stock_description(
                format_string, self.EXAMPLE_PART, self.EXAMPLE_STOCK
            )
        except KeyError as exc:
            error = f"Unknown placeholder {{{exc.args[0]}}}"
        except IndexError:
            error = "Only {0} (description) and {1} (stock) are available"
        except AttributeError as exc:
            error = f"Unknown part attribute: {getattr(exc, 'name', None) or exc}"
        except Exception as exc:
            error = str(exc)
        else:
            return response.Response({"preview": preview})

        return response.Response({"error": error}, status=400)


class CategoryApi(rest_viewsets.ViewSet):
    from .models import SelectedCategory

    queryset = SelectedCategory.objects.all()
    serializer_class = serializers.KicadDetailedCategorySerializer

    def get_serializer(self, *args, **kwargs):
        """Add the parent plugin instance to the serializer contenxt"""
        kwargs["context"] = {"request": self.request}

        return self.serializer_class(*args, **kwargs)

    def get_part_parameter_id_by_name(self, name):
        from common.models import ParameterTemplate

        ret = None
        part_parameter = None

        if isinstance(name, int):
            # an integer was passed to the function -> assume it's the ID already
            ret = name
        elif isinstance(name, str):
            part_parameter = ParameterTemplate.objects.filter(name=name).first()

            if part_parameter:
                ret = part_parameter.pk

        return ret

    def list(self, request):
        from .models import SelectedCategory

        queryset = SelectedCategory.objects.all()
        serializer = serializers.KicadDetailedCategorySerializer(queryset, many=True)

        return response.Response(serializer.data)

    def retrieve(self, request, pk=None):
        from .models import SelectedCategory

        category = get_object_or_404(SelectedCategory, pk=pk)
        serializer = serializers.KicadDetailedCategorySerializer(category)

        return response.Response(serializer.data)

    def partial_update(self, request, pk=None):
        return self.update(request, pk, partial=True)

    def update(self, request, pk=None, **kwargs):
        from .models import SelectedCategory

        category = get_object_or_404(SelectedCategory, pk=pk)

        for parameter in [
            "default_value_parameter_template",
            "footprint_parameter_template",
        ]:
            if parameter in request.data:
                request.data[parameter] = self.get_part_parameter_id_by_name(
                    request.data.pop(parameter)
                )

        serializer = self.get_serializer(
            category, data=request.data, partial=kwargs.get("partial", False)
        )
        serializer.is_valid(raise_exception=True)
        serializer.save()

        return response.Response(serializer.data)

    def create(self, request):
        from common.models import ParameterTemplate
        from part.models import PartCategory

        part_category = get_object_or_404(PartCategory, pk=request.data.get("category"))

        validated_data = {
            "category": part_category,
            "default_symbol": request.data.get("default_symbol", ""),
            "default_footprint": request.data.get("default_footprint", ""),
            "default_reference": request.data.get("default_reference", ""),
        }

        # Add ParameterTemplate keys
        # Allow passing the parameter name instead of the id
        for parameter in [
            "default_value_parameter_template",
            "footprint_parameter_template",
        ]:
            key = "name" if isinstance(request.data.get(parameter), str) else "pk"
            validated_data[parameter] = ParameterTemplate.objects.filter(**{
                key: request.data.get(parameter)
            }).first()

        serializer = serializers.KicadDetailedCategorySerializer()
        created_category = serializer.create(validated_data)

        serializer = serializers.KicadDetailedCategorySerializer(created_category)

        return response.Response(serializer.data)

    def destroy(self, request, pk):
        from .models import SelectedCategory

        category = get_object_or_404(SelectedCategory, pk=pk)
        category.delete()

        return response.Response(status=204)


class CategoryList(generics.ListAPIView):
    """List of available KiCad categories"""

    serializer_class = serializers.KicadCategorySerializer

